import fs from "node:fs";
import path from "node:path";

const tokenFiles = [
  {
    path: "DesignTokens/tokens/1_Primitive_tokens.json",
    assetFolder: "Colors/Primitive",
    naming: "leaf"
  },
  {
    path: "DesignTokens/tokens/2_Semantic_tokens.json",
    assetFolder: "Colors/Semantic",
    naming: "semantic"
  },
  {
    path: "DesignTokens/tokens/3_Component_tokens.json",
    assetFolder: "Colors/Component",
    naming: "semantic"
  }
];

const swiftOutputPath = "Routee-iOS/Routee-iOS/Presentation/Common/Extensions/UIColor+.swift";
const cgFloatOutputPath = "Routee-iOS/Routee-iOS/Presentation/Common/Extensions/CGFloat+.swift";
const assetCatalogPath = "Routee-iOS/Routee-iOS/Presentation/Common/Resources/Assets.xcassets";

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function collectColorTokens(node, pathSegments = [], tokens = []) {
  if (!node || typeof node !== "object") {
    return tokens;
  }

  if (node.$type === "color" && node.$value) {
    tokens.push({
      path: pathSegments,
      value: node.$value
    });
    return tokens;
  }

  Object.entries(node).forEach(([key, value]) => {
    if (!key.startsWith("$")) {
      collectColorTokens(value, [...pathSegments, key], tokens);
    }
  });

  return tokens;
}

function collectNumberTokens(node, pathSegments = [], tokens = []) {
  if (!node || typeof node !== "object") {
    return tokens;
  }

  if (node.$type === "number" && typeof node.$value === "number") {
    tokens.push({
      path: pathSegments,
      value: node.$value
    });
    return tokens;
  }

  Object.entries(node).forEach(([key, value]) => {
    if (!key.startsWith("$")) {
      collectNumberTokens(value, [...pathSegments, key], tokens);
    }
  });

  return tokens;
}

function normalizedName(name) {
  return name.replaceAll("-", "_");
}

function tokenName(pathSegments, naming) {
  const colorPath = pathSegments[0] === "color" ? pathSegments.slice(1) : pathSegments;

  if (naming === "leaf") {
    if (colorPath[0] === "static") {
      return normalizedName(colorPath.join("_"));
    }

    return normalizedName(colorPath[colorPath.length - 1] ?? "");
  }

  if (colorPath[0] === "recap-color-palette") {
    return normalizedName(colorPath[colorPath.length - 1] ?? "");
  }

  const group = colorPath[0] ?? "";
  const leafName = colorPath[colorPath.length - 1] ?? "";
  const normalizedLeafName = normalizedName(leafName);

  if (group && normalizedLeafName.startsWith(`${group}_`)) {
    return normalizedLeafName;
  }

  return normalizedName(colorPath.join("_"));
}

function sortedTokens() {
  return tokenFiles
    .flatMap((file) =>
      collectColorTokens(readJson(file.path)).map((token) => ({
        ...token,
        assetFolder: file.assetFolder,
        naming: file.naming
      }))
    )
    .map((token) => ({
      name: tokenName(token.path, token.naming),
      value: token.value,
      assetFolder: token.assetFolder
    }))
    .sort((lhs, rhs) => lhs.name.localeCompare(rhs.name));
}

function sortedNumberTokens(groupName) {
  const primitiveTokens = readJson("DesignTokens/tokens/1_Primitive_tokens.json");

  return collectNumberTokens(primitiveTokens[groupName])
    .map((token) => ({
      name: token.path[token.path.length - 1] ?? "",
      value: token.value
    }))
    .sort((lhs, rhs) => lhs.value - rhs.value);
}

function colorComponents(token) {
  const [red, green, blue] = token.value.components;
  return {
    red,
    green,
    blue,
    alpha: token.value.alpha
  };
}

function dimensionProperties(prefix, tokens) {
  return tokens
    .map((token) => {
      const suffix = token.name.split("-").at(-1);
      return `    static let ${prefix}${suffix}: CGFloat = ${token.value}`;
    })
    .join("\n");
}

function cgFloatFile(spacingTokens, radiusTokens) {
  const spacingProperties = dimensionProperties("s", spacingTokens);
  const radiusProperties = dimensionProperties("r", radiusTokens);

  return `//
//  CGFloat+.swift
//  Routee-iOS
//
//  Generated by DesignTokens/scripts/build-ios-colors.mjs.
//

import CoreGraphics

// swiftlint:disable identifier_name
extension CGFloat {
${spacingProperties}

${radiusProperties}
}
// swiftlint:enable identifier_name
`;
}

function swiftFile(tokens) {
  const colorProperties = tokens
    .map((token) => {
      const { red, green, blue, alpha } = colorComponents(token);
      return [
        `    static var ${token.name}: UIColor {`,
        "        routeeColor(",
        `            name: "${token.name}",`,
        `            red: ${red.toFixed(6)},`,
        `            green: ${green.toFixed(6)},`,
        `            blue: ${blue.toFixed(6)},`,
        `            alpha: ${alpha.toFixed(6)}`,
        "        )",
        "    }"
      ].join("\n");
    })
    .join("\n\n");

  return `//
//  UIColor+.swift
//  Routee-iOS
//
//  Generated by DesignTokens/scripts/build-ios-colors.mjs.
//

import UIKit

// swiftlint:disable file_length identifier_name
extension UIColor {
${colorProperties}

    private static func routeeColor(
        name: String,
        red: CGFloat,
        green: CGFloat,
        blue: CGFloat,
        alpha: CGFloat
    ) -> UIColor {
        UIColor(named: name) ?? UIColor(
            red: red,
            green: green,
            blue: blue,
            alpha: alpha
        )
    }
}
// swiftlint:enable file_length identifier_name
`;
}

function colorSetContents(token) {
  const { red, green, blue, alpha } = colorComponents(token);

  return {
    colors: [
      {
        idiom: "universal",
        color: {
          "color-space": "srgb",
          components: {
            red: red.toFixed(6),
            green: green.toFixed(6),
            blue: blue.toFixed(6),
            alpha: alpha.toFixed(6)
          }
        }
      }
    ],
    info: {
      author: "xcode",
      version: 1
    }
  };
}

function writeJson(filePath, object) {
  fs.writeFileSync(filePath, `${JSON.stringify(object, null, 2)}\n`);
}

function ensureAssetFolder(folderPath) {
  fs.mkdirSync(folderPath, { recursive: true });
  const contentsPath = path.join(folderPath, "Contents.json");

  if (!fs.existsSync(contentsPath)) {
    writeJson(contentsPath, {
      info: {
        author: "xcode",
        version: 1
      }
    });
  }
}

function cleanGeneratedAssetFolders(tokens) {
  [...new Set(tokens.map((token) => token.assetFolder))]
    .map((assetFolder) => path.join(assetCatalogPath, assetFolder))
    .forEach((assetFolderPath) => {
      if (fs.existsSync(assetFolderPath)) {
        fs.rmSync(assetFolderPath, { recursive: true, force: true });
      }
    });
}

function build() {
  const tokens = sortedTokens();
  const spacingTokens = sortedNumberTokens("spacing");
  const radiusTokens = sortedNumberTokens("radius");

  fs.mkdirSync(path.dirname(swiftOutputPath), { recursive: true });
  fs.writeFileSync(swiftOutputPath, swiftFile(tokens));

  fs.mkdirSync(path.dirname(cgFloatOutputPath), { recursive: true });
  fs.writeFileSync(cgFloatOutputPath, cgFloatFile(spacingTokens, radiusTokens));

  fs.mkdirSync(assetCatalogPath, { recursive: true });
  cleanGeneratedAssetFolders(tokens);

  tokens.forEach((token) => {
    const assetFolderPath = path.join(assetCatalogPath, token.assetFolder);
    ensureAssetFolder(assetFolderPath);

    const colorSetPath = path.join(assetFolderPath, `${token.name}.colorset`);
    fs.mkdirSync(colorSetPath, { recursive: true });
    writeJson(path.join(colorSetPath, "Contents.json"), colorSetContents(token));
  });
}

build();
